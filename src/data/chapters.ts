// Helper to generate Enemy Templates per tier
const createEnemy = (
  name: string,
  type: 'melee' | 'archer' | 'brute' | 'caster' | 'boss',
  tier: number,
  specialSkill?: 'charge' | 'fireball' | 'whirlwind' | 'frostNova' | 'meteor' | 'voidBeam'
): EnemyTemplate => {
  const baseHp = type === 'boss' ? 700 + tier * 320 : type === 'brute' ? 140 + tier * 45 : type === 'caster' ? 80 + tier * 25 : type === 'archer' ? 60 + tier * 20 : 70 + tier * 22;
  const baseDmg = type === 'boss' ? 30 + tier * 7 : type === 'brute' ? 18 + tier * 4 : 10 + tier * 3;
  const baseSpeed = type === 'archer' ? 1.6 : type === 'brute' ? 1.2 : type === 'boss' ? 1.4 : 1.8;

  let color = '#22c55e';
  if (tier >= 25) color = '#c084fc';
  else if (tier >= 20) color = '#38bdf8';
  else if (tier >= 15) color = '#818cf8';
  else if (tier >= 10) color = '#f97316';
  else if (tier >= 5) color = '#a855f7';

  return {
    name,
    type,
    maxHp: Math.round(baseHp),
    damage: Math.round(baseDmg),
    speed: baseSpeed,
    color,
    size: type === 'boss' ? 44 : type === 'brute' ? 26 : 20,
    attackRange: type === 'archer' || type === 'caster' ? 240 : type === 'boss' ? 80 : 38,
    attackCooldown: type === 'boss' ? 1100 : type === 'archer' ? 1600 : 900,
    points: 100 * tier,
    gold: type === 'boss' ? 300 + tier * 25 : 8 + Math.round(tier * 2.5),
    specialSkill,
  };
};

